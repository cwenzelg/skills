// contract.mjs - the ONE structure every design system has (references/specimen-structure.md): the
// ordered sections of its specimen page and the files of its folder. Taken from the two template
// systems (Loop Studio, Tap2Link Harbor), which share exactly this. specimen.mjs renders from it,
// check-system.mjs enforces it, and the Cluster Console reads it to show the same header, section
// navigation and completeness badge for every system. Dependency-free; never throws on a bad folder.

import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

export const CONTRACT_VERSION = 1;

/**
 * The specimen's sections in page order. `when`: `always` = every system; `open-points` = when DESIGN.md has an
 * "Open points ..." section with items; `recipes` = when the tokens hold a ground, gradient, glass or blur recipe.
 */
export const SPECIMEN_SECTIONS = Object.freeze([
  { id: 'character', label: 'Character and rules', when: 'always' },
  { id: 'open', label: 'Open points', when: 'open-points' },
  { id: 'colour', label: 'Colour', when: 'always' },
  { id: 'recipes', label: 'Grounds and effects', when: 'recipes' },
  { id: 'type', label: 'Typography', when: 'always' },
  { id: 'shape', label: 'Shape', when: 'always' },
  { id: 'foundations', label: 'Foundations', when: 'always' },
  { id: 'components', label: 'Components', when: 'always' },
  { id: 'reference', label: 'Reference screens', when: 'always' },
  { id: 'files', label: 'Files and checks', when: 'always' },
]);

/** The specimen carries this line in its footer; a hand-made page does not. */
export const GENERATED_MARK = /Generated by the design-system skill's specimen\.mjs/;

/** Files and folders of the template that every system has, whatever its tokens say. */
export const TEMPLATE_FILES = Object.freeze([
  'system.json', 'DESIGN.md', 'llms.txt',
  'tokens/primitives.tokens.json', 'tokens/semantic.light.tokens.json', 'tokens/semantic.dark.tokens.json', 'tokens/components.tokens.json',
  'build/tokens.css', 'build/tokens.resolved.json',
  'foundations/color.md', 'foundations/typography.md', 'foundations/elevation.md', 'foundations/iconography.md',
  'specimen/index.html',
  'checks/CHECKLIST.md', 'checks/contrast-pairs.json',
]);

/** The sections DESIGN.md must have (the specimen builds its character, files and status blocks from them). */
export const DESIGN_SECTIONS = Object.freeze([
  { re: /^character\b/i, label: 'Character' },
  { re: /^rules\b/i, label: 'Rules (always / never)' },
  { re: /^files\b/i, label: 'Files' },
  { re: /^status\b/i, label: 'Status' },
]);

const IMAGE = /\.(png|jpe?g|webp)$/i;
const read = (p) => { try { return readFileSync(p, 'utf8'); } catch { return ''; } };

/** The `id`s of the top-level `<section>`s of a specimen page, in page order. */
export function sectionIds(html) {
  return [...String(html ?? '').matchAll(/<section id="([\w-]+)"/g)].map((m) => m[1]);
}

/** The template gaps of a folder (files, DESIGN.md sections, a don't image, one html snippet per component spec): plain strings. */
export function templateGaps(dir) {
  const gaps = [];
  for (const f of TEMPLATE_FILES) if (!existsSync(join(dir, f))) gaps.push(`missing ${f}`);
  const design = read(join(dir, 'DESIGN.md'));
  if (design) {
    const headings = [...design.matchAll(/^##\s+(.+?)\s*$/gm)].map((m) => m[1]);
    for (const s of DESIGN_SECTIONS) if (!headings.some((h) => s.re.test(h))) gaps.push(`DESIGN.md has no "## ${s.label}" section`);
  }
  const dont = join(dir, 'reference', 'dont');
  let dontImages = [];
  try { dontImages = readdirSync(dont).filter((f) => IMAGE.test(f)); } catch { /* none */ }
  if (dontImages.length === 0) gaps.push('reference/dont/ holds no image - the typical mistakes belong to the template');
  let specs = [];
  try { specs = readdirSync(join(dir, 'components')).filter((f) => f.endsWith('.md')); } catch { /* none */ }
  if (specs.length === 0) gaps.push('components/ holds no component spec');
  for (const s of specs) if (!existsSync(join(dir, 'components', s.replace(/\.md$/, '.html')))) gaps.push(`components/${s} has no ${s.replace(/\.md$/, '.html')} snippet`);
  return gaps;
}

/**
 * Specimen gaps: the page is generated by specimen.mjs and holds every section the contract expects for THIS system.
 * `expected` = the ids a fresh specimen.mjs run produces (so a conditional section is required exactly when it applies).
 *
 * @param {string} dir
 * @param {string[]} expected
 */
export function specimenGaps(dir, expected) {
  const file = join(dir, 'specimen', 'index.html');
  if (!existsSync(file)) return [];
  const html = read(file);
  const have = new Set(sectionIds(html));
  const gaps = [];
  if (!GENERATED_MARK.test(html)) gaps.push('specimen/index.html was not generated by specimen.mjs (hand-made page) - run: node specimen.mjs <system>');
  for (const id of ['top', ...expected]) {
    if (have.has(id)) continue;
    const label = SPECIMEN_SECTIONS.find((s) => s.id === id)?.label ?? id;
    gaps.push(`specimen/index.html lacks the section "${label}" (#${id}) - regenerate it with specimen.mjs`);
  }
  return gaps;
}
