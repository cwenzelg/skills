#!/usr/bin/env node
// build-tokens.mjs - DTCG token files -> CSS custom properties per mode and brand, plus a resolved
// JSON every other check reads. The build/ folder is generated: never edit it by hand.
//
//   node build-tokens.mjs <system folder> [--out <dir>]      (default <system>/build)
//
// Writes  <out>/tokens.css            :root = default mode; [data-theme="<mode>"] per mode;
//                                      prefers-color-scheme: dark when no data-theme is set, unless system.json
//                                      has "defaultMode" (e.g. "light": the page stays in that mode until chosen);
//                                      [data-brand="<b>"] (+ [data-theme]) with only what the brand changes
//         <out>/tokens.resolved.json   every token per combination: path, type, tier, css value
// Exit codes: 0 written · 1 a token file is broken (bad alias, cycle, missing mode file) · 2 usage.

import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cssVars, loadSystem, resolveAll } from './lib/tokens.mjs';

const block = (selector, vars) => `${selector} {\n${[...vars].map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`;
const diff = (vars, base) => new Map([...vars].filter(([k, v]) => base.get(k) !== v));

export function buildCss(system, resolved = resolveAll(system)) {
  const [first, ...rest] = system.modes;
  const vars = Object.fromEntries(Object.entries(resolved).map(([k, v]) => [k, cssVars(v)]));
  let css = `/* Generated by build-tokens.mjs from ${system.name} - do not edit by hand. */\n`;
  const imports = system.config.fontImports ?? [];
  css = imports.map((u) => `@import url("${u}");\n`).join('') + css;
  css += block(`:root, [data-theme="${first}"]`, vars[first]);
  for (const m of rest) {
    css += block(`[data-theme="${m}"]`, vars[m]);
    if (m === 'dark' && !system.config.defaultMode) css += `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme])', vars[m]).replace(/^/gm, '  ').trimEnd()}\n}\n`;
  }
  for (const b of Object.keys(system.brands)) {
    for (const m of system.modes) {
      const own = diff(vars[`brand:${b}:${m}`], vars[m]);
      if (own.size === 0) continue;
      const sel = m === first ? `[data-brand="${b}"], [data-brand="${b}"][data-theme="${m}"]` : `[data-brand="${b}"][data-theme="${m}"]`;
      css += block(sel, own);
    }
  }
  return css;
}

export function buildJson(system, resolved = resolveAll(system)) {
  const out = { name: system.name, modes: system.modes, brands: Object.keys(system.brands), sets: {} };
  for (const [k, set] of Object.entries(resolved)) {
    out.sets[k] = Object.fromEntries([...set.values()].map((t) => [t.path, { type: t.type, tier: t.tier, css: t.css, alias: t.alias, ...(t.stops ? { stops: t.stops } : {}) }]));
  }
  return out;
}

export function build(dir, outDir = join(dir, 'build')) {
  const system = loadSystem(dir);
  const resolved = resolveAll(system);
  mkdirSync(outDir, { recursive: true });
  const cssFile = join(outDir, 'tokens.css');
  const jsonFile = join(outDir, 'tokens.resolved.json');
  writeFileSync(cssFile, buildCss(system, resolved));
  writeFileSync(jsonFile, JSON.stringify(buildJson(system, resolved), null, 2) + '\n');
  return { cssFile, jsonFile, system };
}

function main(argv) {
  const args = argv.filter((a) => !a.startsWith('--'));
  const outIdx = argv.indexOf('--out');
  if (!args[0] || argv.includes('--help')) {
    console.error('usage: node build-tokens.mjs <system folder> [--out <dir>]');
    return argv.includes('--help') ? 0 : 2;
  }
  const dir = resolve(args[0]);
  try {
    const { cssFile, jsonFile } = build(dir, outIdx >= 0 ? resolve(argv[outIdx + 1]) : undefined);
    console.log(`wrote ${cssFile}\nwrote ${jsonFile}`);
    return 0;
  } catch (e) {
    console.error(`error ${e.message}`);
    return 1;
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
